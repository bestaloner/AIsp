    '或防护栏杆不完整——缺少上横杆、下横杆，或者立杆间距超过 2 米，或者栏杆高度'
    '不足 1.2 米。第二，外脚手架没有与主体结构同步搭设，导致建筑物上部临边悬空。'
    '第三，各类洞口——包括楼梯口、电梯井口、预留洞口——没有设置防护栏杆或盖板覆盖。'
    '按照 JGJ 80-2016 第 4.2.1 条的规定：竖向洞口短边小于 500mm 时应封堵，'
